"""Resolve the released core coordinate from a copied repository, without SDK sources."""

from __future__ import annotations

import argparse
import base64
import json
import subprocess
import tempfile
from pathlib import Path

from release import ROOT, version

PROBE = """
import io.metor.license.core.*;
import java.nio.file.*;

public class MavenConsumer {
    public static void main(String[] args) throws Exception {
        byte[] config = Files.readAllBytes(Path.of(args[0]));
        Path root = Path.of(args[1]);
        var created = LicenseInstallation.initialize(config, root);
        if (!LicenseInstallation.validate(config, root).equals(created.installationId()))
            throw new AssertionError("Read-only check returned a different installation");
        try (var runtime = LicenseRuntime.fromConfig(config, root, "api")) {
            try {
                runtime.importLicense(new byte[0], null, "0");
                throw new AssertionError("Empty candidate accepted");
            } catch (OnboardingException expected) {
                if (expected.code() != OnboardingException.Code.CANDIDATE_REJECTED) throw expected;
            }
        }
        System.out.println("PASS: detached Maven consumer, initialization and new APIs");
    }
}
"""


def verify(repository: Path, gradle: Path, *, offline: bool) -> None:
    release = version()
    with tempfile.TemporaryDirectory(prefix="license-maven-consumer-") as directory:
        consumer = Path(directory)
        (consumer / "settings.gradle").write_text("rootProject.name = 'detached-consumer'\n")
        # The probe has exactly one repository and never consults Maven Local or sibling builds.
        (consumer / "build.gradle").write_text(
            "plugins { id 'java' }\n"
            f"repositories {{ maven {{ url = uri('{repository.as_uri()}') }} }}\n"
            f"dependencies {{ implementation 'io.metor.license:license-core:{release}' }}\n"
            "tasks.register('smoke', JavaExec) {\n"
            "  dependsOn classes; classpath = sourceSets.main.runtimeClasspath\n"
            "  mainClass = 'MavenConsumer'; args 'config.json', 'license-data'\n"
            "}\n"
        )
        sources = consumer / "src/main/java"
        sources.mkdir(parents=True)
        (sources / "MavenConsumer.java").write_text(PROBE)
        # A public synthetic Ed25519 key, generated by the JDK from a fixed valid SPKI vector.
        der = base64.b64encode(bytes.fromhex("302a300506032b6570032100") + bytes(range(32)))
        config = {
            "schema_version": 1,
            "product_id": "maven-smoke",
            "fingerprint_domain": "maven-smoke/fp/v1",
            "binding_domain": "maven-smoke/bind/v1",
            "recovery_domain": "maven-smoke/recovery/v1",
            "request_prefix": "MS1",
            "services": [{"id": "api", "recovery_prefix": "MS1A"}],
            "trusted_keys": {
                "synthetic": "-----BEGIN PUBLIC KEY-----\n"
                + der.decode()
                + "\n-----END PUBLIC KEY-----\n"
            },
        }
        (consumer / "config.json").write_text(json.dumps(config))
        command = [str(gradle), "--no-daemon", "--console=plain"]
        if offline:
            command.append("--offline")
        subprocess.run([*command, "smoke"], cwd=consumer, check=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", required=True, type=Path)
    parser.add_argument("--gradle", type=Path, default=ROOT / "java/gradlew")
    parser.add_argument("--offline", action="store_true")
    args = parser.parse_args()
    verify(args.repository.resolve(), args.gradle.resolve(), offline=args.offline)


if __name__ == "__main__":
    main()
